#!/usr/bin/env node
/**
 * D6.0 — Bundle @walkcroach/desktop-agent (+ inlined @walkcroach/agent-engine)
 * into a single CJS file the Agent Host can load in packaged builds.
 *
 * Format is **cjs** (not esm): AWS SDK and MCP SDK are CommonJS-heavy; esbuild's
 * ESM `require` shim rejects `node:` builtins. Agent Host loads via createRequire.
 *
 * Outputs:
 *   packages/desktop-agent/dist-bundle/engine-bundle.cjs
 *   vscode/.../walkcroach/media/engine-bundle.cjs  (when vscode present)
 *   vscode/out/.../media/engine-bundle.cjs         (when out/ present)
 */
import * as esbuild from 'esbuild';
import { mkdirSync, copyFileSync, existsSync, writeFileSync, readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const desktopRoot = join(pkgRoot, '..', '..');
const entry = join(pkgRoot, 'src', 'index.ts');
const distBundleDir = join(pkgRoot, 'dist-bundle');
const primaryOut = join(distBundleDir, 'engine-bundle.cjs');

const mediaRel = join(
  'src',
  'vs',
  'platform',
  'agentHost',
  'node',
  'walkcroach',
  'media',
  'engine-bundle.cjs',
);
const vscodeSrcMedia = join(desktopRoot, 'vscode', mediaRel);
const vscodeOutMedia = join(
  desktopRoot,
  'vscode',
  'out',
  'vs',
  'platform',
  'agentHost',
  'node',
  'walkcroach',
  'media',
  'engine-bundle.cjs',
);

mkdirSync(distBundleDir, { recursive: true });

const result = await esbuild.build({
  entryPoints: [entry],
  outfile: primaryOut,
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node20',
  sourcemap: false,
  packages: 'bundle',
  external: ['node-pty', 'node-pty-prebuilt-multiarch'],
  logLevel: 'info',
  banner: {
    js: [
      '/* WalkCroach desktop-agent engine-bundle — D6.0 / D3 packaging */',
      '/* Do not edit: generated by packages/desktop-agent/scripts/bundle-engine.mjs */',
    ].join('\n'),
  },
  metafile: true,
});

writeFileSync(
  join(distBundleDir, 'engine-bundle.meta.json'),
  JSON.stringify(result.metafile, null, 2),
);

function mirror(dest) {
  mkdirSync(dirname(dest), { recursive: true });
  copyFileSync(primaryOut, dest);
  console.log(`[bundle-engine] wrote ${dest}`);
}

if (existsSync(join(desktopRoot, 'vscode', 'src', 'vs', 'platform', 'agentHost', 'node', 'walkcroach'))) {
  mirror(vscodeSrcMedia);
} else {
  console.warn('[bundle-engine] vscode walkcroach provider missing — skipped src media mirror');
}

if (existsSync(join(desktopRoot, 'vscode', 'out'))) {
  mirror(vscodeOutMedia);
}

const require = createRequire(import.meta.url);
const mod = require(primaryOut);
const required = ['createSessionHost', 'startDesktopSession', 'FileSecrets', 'MemorySecrets', 'SECRET_KEYS'];
for (const name of required) {
  if (mod[name] == null) {
    console.error(`[bundle-engine] missing export: ${name}`);
    process.exit(1);
  }
}

const bytes = readFileSync(primaryOut).byteLength;
console.log(`[bundle-engine] ok ${primaryOut} (${(bytes / (1024 * 1024)).toFixed(2)} MiB)`);
void require;
