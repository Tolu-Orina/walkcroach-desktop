#!/usr/bin/env node
/**
 * Build a Windows Inno Setup installer from the gulp package folder.
 *
 * Uses ISCC from vscode/node_modules/innosetup (or INNO_ISCC env / PATH).
 * Currently UNSIGNED — SmartScreen will warn. Pass --sign only once a real
 * SignTool is configured in Inno (see packaging/inno/walkcroach.iss).
 *
 * Usage:
 *   node scripts/make-windows-inno.mjs <packageRoot> <outExePath> [--machine] [--sign] [--debug]
 *
 * Flags:
 *   --machine  per-machine install (Program Files, requires admin). Default: per-user.
 *   --sign     enable the SignTool stanza. Fails unless INNO_SIGN_TOOL is set.
 *   --debug    emit the preprocessed .iss next to the source for inspection.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, basename, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);

const argv = process.argv.slice(2);
const flags = new Set(argv.filter((a) => a.startsWith('--')));
const positional = argv.filter((a) => !a.startsWith('--'));
const packageRoot = positional[0] ? resolve(positional[0]) : '';
const outExe = positional[1] ? resolve(positional[1]) : '';
const installTarget = flags.has('--machine') ? 'machine' : 'user';
const wantSign = flags.has('--sign');
const wantDebug = flags.has('--debug');

if (!packageRoot || !outExe) {
  console.error(
    'Usage: node scripts/make-windows-inno.mjs <packageRoot> <outExePath> [--machine] [--sign] [--debug]',
  );
  process.exit(1);
}
if (!existsSync(packageRoot)) {
  console.error(`packageRoot missing: ${packageRoot}`);
  process.exit(1);
}

const vscodeRepo = join(root, 'vscode');

const productPath = existsSync(join(packageRoot, 'resources', 'app', 'product.json'))
  ? join(packageRoot, 'resources', 'app', 'product.json')
  : join(vscodeRepo, 'product.json');
const product = JSON.parse(readFileSync(productPath, 'utf8'));
const pkgJsonPath = join(vscodeRepo, 'package.json');
const pkg = existsSync(pkgJsonPath)
  ? JSON.parse(readFileSync(pkgJsonPath, 'utf8'))
  : { version: product.version || '0.0.0' };

/** ExeBasename must match what gulp emitted (product.nameShort), not a guess. */
const exeBasename = product.nameShort || 'WalkCroach';
if (!existsSync(join(packageRoot, `${exeBasename}.exe`))) {
  console.error(
    `[make-windows-inno] ${exeBasename}.exe not found in ${packageRoot}\n` +
      'The package folder looks incomplete or product.nameShort disagrees with the build.',
  );
  process.exit(1);
}

const arch = packageRoot.includes('arm64') ? 'arm64' : 'x64';

/**
 * Inno 6.3 deprecated the bare `x64` identifier in favour of `x64compatible`
 * (same meaning: x64 OS *or* an OS that can run x64 binaries, e.g. ARM64).
 * `arm64` is unchanged. Using the modern spelling avoids a compiler warning.
 */
const archIdentifier = arch === 'arm64' ? 'arm64' : 'x64compatible';

const appIdRaw =
  (installTarget === 'machine'
    ? arch === 'arm64'
      ? product.win32arm64AppId
      : product.win32x64AppId
    : arch === 'arm64'
      ? product.win32arm64UserAppId
      : product.win32x64UserAppId) || '{A4A2A37C-F6BC-43A5-A9BE-07FB53D9D387}';
// Inno define: a literal `{` in AppId must be doubled -> {{GUID}
const appId = String(appIdRaw).startsWith('{{')
  ? appIdRaw
  : `{{${String(appIdRaw).replace(/^\{|\}$/g, '')}}`;

/**
 * Expand packaging/inno/file-associations.json into [Registry] entries.
 *
 * Generated rather than hand-written: ~46 file types x 7 registry rows is 300+
 * near-identical lines that drift silently when edited by hand.
 */
function generateAssociations() {
  const dataPath = join(root, 'packaging', 'inno', 'file-associations.json');
  const { associations } = JSON.parse(readFileSync(dataPath, 'utf8'));
  const iconDir = join(vscodeRepo, 'resources', 'win32');

  const lines = [
    '; GENERATED by scripts/make-windows-inno.mjs from packaging/inno/file-associations.json',
    '; Do not edit — changes are overwritten on every build.',
    '',
  ];

  const seen = new Set();
  for (const { ext, icon, label } of associations) {
    if (!ext?.startsWith('.') || !icon || !label) {
      throw new Error(`Malformed association entry: ${JSON.stringify({ ext, icon, label })}`);
    }
    if (seen.has(ext)) {
      throw new Error(`Duplicate association for ${ext} in file-associations.json`);
    }
    seen.add(ext);
    // A comma would be parsed as the next {cm:...} argument and silently truncate the label.
    if (label.includes(',')) {
      throw new Error(`Association label for ${ext} must not contain a comma: "${label}"`);
    }
    if (!existsSync(join(iconDir, `${icon}.ico`))) {
      throw new Error(
        `Association ${ext} references missing icon ${icon}.ico (looked in ${iconDir})`,
      );
    }

    const key = ext.slice(1);
    const progid = `{#RegValueName}.${key}`;
    const iconPath = `{app}\\resources\\app\\resources\\win32\\${icon}.ico`;
    const exe = '{app}\\{#ExeBasename}.exe';
    const root_ = '{#SoftwareClassesRootKey}';
    const task = 'Tasks: associatewithfiles';

    lines.push(
      `Root: ${root_}; Subkey: "Software\\Classes\\${ext}\\OpenWithProgids"; ValueType: none; ValueName: "{#RegValueName}"; Flags: deletevalue uninsdeletevalue; ${task}`,
      `Root: ${root_}; Subkey: "Software\\Classes\\${ext}\\OpenWithProgids"; ValueType: string; ValueName: "${progid}"; ValueData: ""; Flags: uninsdeletevalue; ${task}`,
      `Root: ${root_}; Subkey: "Software\\Classes\\${progid}"; ValueType: string; ValueName: ""; ValueData: "{cm:SourceFile,${label}}"; Flags: uninsdeletekey; ${task}`,
      `Root: ${root_}; Subkey: "Software\\Classes\\${progid}"; ValueType: string; ValueName: "AppUserModelID"; ValueData: "{#AppUserModelId}"; Flags: uninsdeletekey; ${task}`,
      `Root: ${root_}; Subkey: "Software\\Classes\\${progid}\\DefaultIcon"; ValueType: string; ValueName: ""; ValueData: "${iconPath}"; ${task}`,
      `Root: ${root_}; Subkey: "Software\\Classes\\${progid}\\shell\\open"; ValueType: string; ValueName: "Icon"; ValueData: """${exe}"""; ${task}`,
      `Root: ${root_}; Subkey: "Software\\Classes\\${progid}\\shell\\open\\command"; ValueType: string; ValueName: ""; ValueData: """${exe}"" ""%1"""; ${task}`,
      '',
    );
  }

  const outDir = join(root, 'packaging', 'inno', 'generated');
  mkdirSync(outDir, { recursive: true });
  const outPath = join(outDir, 'associations.iss');
  writeFileSync(outPath, lines.join('\n'), 'utf8');
  console.log(`[make-windows-inno] generated associations.iss (${seen.size} file types)`);
  return outPath;
}

function findIscc() {
  if (process.env.INNO_ISCC && existsSync(process.env.INNO_ISCC)) {
    return process.env.INNO_ISCC;
  }
  try {
    const innosetupPkg = require.resolve('innosetup/package.json', {
      paths: [vscodeRepo],
    });
    const candidate = join(dirname(innosetupPkg), 'bin', 'ISCC.exe');
    if (existsSync(candidate)) return candidate;
  } catch {
    /* fall through */
  }
  const where = spawnSync('where.exe', ['ISCC.exe'], { encoding: 'utf8', shell: true });
  const first = (where.stdout || '').split(/\r?\n/).map((s) => s.trim()).find(Boolean);
  return first && existsSync(first) ? first : null;
}

const iscc = findIscc();
if (!iscc) {
  console.error(`
[make-windows-inno] ISCC.exe not found.
Install Inno Setup or ensure vscode/node_modules/innosetup is present
(cd vscode && npm ci). Or set INNO_ISCC to ISCC.exe.
`);
  process.exit(1);
}

const iss = join(root, 'packaging', 'inno', 'walkcroach.iss');
if (!existsSync(iss)) {
  console.error(`missing ${iss}`);
  process.exit(1);
}

if (wantSign && !process.env.INNO_SIGN_TOOL) {
  console.error(
    '[make-windows-inno] --sign requires INNO_SIGN_TOOL (an Inno SignTool named "walkcroach").',
  );
  process.exit(1);
}

generateAssociations();

const version = String(pkg.version || product.version || '0.0.0');
const rawVersion = version.replace(/-\w+$/, '') || '0.0.0';
const outputDir = dirname(outExe);
const outputBase = basename(outExe, '.exe');
mkdirSync(outputDir, { recursive: true });
if (existsSync(outExe)) unlinkSync(outExe);

const defs = {
  AppName: product.nameLong || 'WalkCroach Desktop',
  AppVersion: version,
  RawVersion: rawVersion,
  AppPublisher: 'WalkCroach',
  AppId: appId,
  Arch: archIdentifier,
  ArchInstallIn64BitMode: archIdentifier,
  SourceDir: packageRoot,
  OutputDir: outputDir,
  OutputBaseFilename: outputBase,
  ExeBasename: exeBasename,
  DirName: product.win32DirName || 'WalkCroach',
  AppUserModelId: product.win32AppUserModelId || 'WalkCroach.Desktop',
  NameShort: product.nameShort || 'WalkCroach',
  ApplicationName: product.applicationName || 'walkcroach',
  RegValueName: product.win32RegValueName || 'WalkCroach',
  ShellNameShort: product.win32ShellNameShort || product.nameShort || 'WalkCroach',
  AppMutex: product.win32MutexName || 'walkcroach',
  RepoDir: vscodeRepo,
  InstallTarget: installTarget,
};
if (wantSign) defs.Sign = '1';
if (wantDebug) defs.Debug = '1';

const args = [iss, ...Object.entries(defs).map(([k, v]) => `/d${k}=${v}`)];
console.log(
  `==> ISCC ${outputBase}.exe (arch=${arch}/${archIdentifier}, target=${installTarget}, ${wantSign ? 'signed' : 'unsigned'})`,
);
const r = spawnSync(iscc, args, { stdio: 'inherit', env: process.env, windowsHide: true });
if (r.status !== 0) {
  console.error(`[make-windows-inno] ISCC failed (${r.status})`);
  process.exit(r.status ?? 1);
}

if (!existsSync(outExe)) {
  console.error(`[make-windows-inno] expected output missing: ${outExe}`);
  process.exit(1);
}

console.log(`[make-windows-inno] ${outExe}`);
if (!wantSign) {
  console.log('[make-windows-inno] unsigned preview — SmartScreen will warn');
}
